type ThresholdMetricSeed = {
  metric: ReturnType<typeof t>;
  value: string;
  maxScore?: string;
  sourceIds?: string[];
  note?: ReturnType<typeof t>;
};

type ThresholdYearSeed = {
  year: string;
  sitting?: string;
  status?: ThresholdRecord["status"];
  sourceIds?: string[];
  note?: ReturnType<typeof t>;
  metrics: ThresholdMetricSeed[];
};

const metric = (
  zh: string,
  en: string,
  value: string,
  maxScore?: string,
  note?: ReturnType<typeof t>,
): ThresholdMetricSeed => ({ metric: t(zh, en), value, maxScore, note });

const expandThresholds = (
  projectId: string,
  defaultSourceIds: string[],
  rows: ThresholdYearSeed[],
): ThresholdRecord[] => rows.flatMap((row) => row.metrics.map((entry) => {
  const key = [projectId, row.year, row.sitting, entry.metric.en]
    .filter(Boolean)
    .join("-")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
  return {
    id: key,
    projectId,
    year: row.year,
    sitting: row.sitting,
    metric: entry.metric,
    value: entry.value,
    maxScore: entry.maxScore,
    status: row.status ?? "historical",
    sourceIds: entry.sourceIds ?? row.sourceIds ?? defaultSourceIds,
    note: entry.note ?? row.note,
  };
}));

