const sourceById = new Map(journalSources.map((source) => [source.id, source]));

function journalLink(sourceId: string, kind: JournalRecord["links"][number]["kind"], note?: ReturnType<typeof t>): JournalRecord["links"][number] {
  const source = sourceById.get(sourceId);
  if (!source) throw new Error(`Unknown journal source: ${sourceId}`);
  return { label: source.label, url: source.url, kind, ...(note ? { note } : {}) };
}

