const source = (
  id: string,
  labelZh: string,
  labelEn: string,
  ownerZh: string,
  ownerEn: string,
  url: string,
  kind: SourceRecord["kind"],
  appliesTo: string,
  noteZh?: string,
  noteEn?: string,
): SourceRecord => ({
  id,
  label: t(labelZh, labelEn),
  owner: t(ownerZh, ownerEn),
  url,
  kind,
  verifiedAt: VERIFIED_AT,
  appliesTo,
  ...(noteZh && noteEn ? { note: t(noteZh, noteEn) } : {}),
});

const fact = (
  labelZh: string,
  labelEn: string,
  valueZh: string,
  valueEn: string,
  sourceIds: string[],
  status: FactRecord["status"] = "confirmed",
): FactRecord => ({
  label: t(labelZh, labelEn),
  value: t(valueZh, valueEn),
  status,
  sourceIds,
});

const row = (
  cells: Array<[string, string]>,
  sourceIds?: string[],
): TableRow => ({
  cells: cells.map(([zh, en]) => t(zh, en)),
  status: "confirmed",
  ...(sourceIds ? { sourceIds } : {}),
});

